// Turns the website's data files (areas, fields, skills, sample members, the demo member's history)
// into plain INSERT statements in db/seed.sql, so the database and the website start from the same data.
// Run: npm run db:seed:build
import { build } from 'esbuild'
import { writeFileSync, mkdtempSync, rmSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { tmpdir } from 'node:os'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { randomBytes } from 'node:crypto'
import bcrypt from 'bcryptjs'

const here = dirname(fileURLToPath(import.meta.url))
const client = join(here, '..', '..', 'client')

// Bundle the website's data modules so Node can read them (they import icons the website draws).
const tmp = mkdtempSync(join(tmpdir(), 'oren-seed-'))
const entry = join(tmp, 'entry.mjs')
writeFileSync(entry, [
  `export { AREAS, FIELDS } from ${JSON.stringify(join(client, 'src/data/fields.js').replace(/\\/g, '/'))}`,
  `export { SKILLS } from ${JSON.stringify(join(client, 'src/data/skills.js').replace(/\\/g, '/'))}`,
  `export { SAMPLE_PEOPLE as PEOPLE, DEMO_ME, DEMO_GROWTH } from ${JSON.stringify(join(client, 'src/data/people.js').replace(/\\/g, '/'))}`,
].join('\n'))
const outfile = join(tmp, 'data.mjs')
await build({ entryPoints: [entry], bundle: true, platform: 'node', format: 'esm', outfile, logLevel: 'error', nodePaths: [join(client, 'node_modules')], loader: { '.json': 'json' } })
const { AREAS, FIELDS, SKILLS, PEOPLE, DEMO_ME, DEMO_GROWTH } = await import(pathToFileURL(outfile).href)
rmSync(tmp, { recursive: true, force: true })

// ── SQL helpers ──
const lit = (v) => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : typeof v === 'boolean' ? (v ? 'TRUE' : 'FALSE') : `'${String(v).replace(/'/g, "''")}'`)
const row = (vals) => `(${vals.map(lit).join(', ')})`
const insert = (table, cols, rows, tail = '') => (rows.length ? `INSERT INTO ${table} (${cols.join(', ')}) VALUES\n  ${rows.map(row).join(',\n  ')}${tail};\n` : '')
const uid = (handle) => ({ raw: `pg_temp.uid(${lit(handle)})` })
// rows may contain {raw} values that must not be quoted
const rowRaw = (vals) => `(${vals.map((v) => (v && typeof v === 'object' && 'raw' in v ? v.raw : lit(v))).join(', ')})`
const insertRaw = (table, cols, rows, tail = '') => (rows.length ? `INSERT INTO ${table} (${cols.join(', ')}) VALUES\n  ${rows.map(rowRaw).join(',\n  ')}${tail};\n` : '')

const DAYS = ['sun', 'mon', 'tue', 'wed', 'thu', 'fri', 'sat']
const MONTHS = { Jan: '01', Feb: '02', Mar: '03', Apr: '04', May: '05', Jun: '06', Jul: '07', Aug: '08', Sep: '09', Oct: '10', Nov: '11', Dec: '12' }
const joinedOn = (s) => { const [m, y] = String(s).split(' '); return MONTHS[m] && y ? `${y}-${MONTHS[m]}-01` : '2026-01-01' }
const year = (s) => (/^\d{4}$/.test(String(s)) ? +s : null)
const iconOf = (s) => (s.icon ? ['brand', s.icon] : s.glyph ? ['symbol', s.glyph] : ['letters', s.mono || null])

const out = []
out.push(`-- Generated by scripts/build-seed.mjs from the website's data files. Do not edit by hand.
-- ${AREAS.length} areas, ${FIELDS.length} fields, ${SKILLS.length} skills, ${PEOPLE.length} sample members and the demo member's history.
SET client_min_messages = warning;
CREATE FUNCTION pg_temp.uid(h text) RETURNS bigint LANGUAGE sql STABLE AS $$ SELECT id FROM users WHERE handle = h $$;
`)

// ── Catalog ──
out.push('-- Catalog')
out.push(insert('areas', ['id', 'name', 'short_name', 'hue', 'position'], AREAS.map((a, i) => [a.id, a.name, a.short, a.h, i])))
out.push(insert('fields', ['id', 'area_id', 'name', 'short_name', 'blurb', 'hue', 'position'], FIELDS.map((f, i) => [f.id, f.area, f.name, f.short, f.blurb, f.h, i])))
out.push(insert('skills', ['id', 'field_id', 'name', 'icon_kind', 'icon'], SKILLS.map((s) => [s.id, s.field, s.name, ...iconOf(s)])))

// ── Sample members ──
out.push('-- Sample members')
out.push(insert('users',
  ['handle', 'name', 'headline', 'bio', 'teach_style', 'city', 'country', 'tz_offset', 'main_field', 'meets_online', 'meets_in_person', 'github', 'member_no', 'joined_on', 'is_sample', 'likes_newcomers', 'prior_taught', 'prior_learned', 'prior_rating', 'reply_time'],
  PEOPLE.map((p) => [p.handle, p.name, p.headline, p.bio, p.style, p.city, p.country, p.tz, p.field, p.format.includes('online'), p.format.includes('in-person'), p.github || null, p.number, joinedOn(p.joined), true, !!(p.likesYou || p.requestedYou), p.stats.taught, p.stats.learned, p.stats.rating, p.stats.reply])))
out.push(insertRaw('user_languages', ['user_id', 'language'], PEOPLE.flatMap((p) => p.languages.map((l) => [uid(p.handle), l]))))
out.push(insertRaw('education', ['user_id', 'kind', 'title', 'place', 'from_year', 'to_year', 'ongoing', 'position'],
  PEOPLE.flatMap((p) => p.education.map((e, i) => [uid(p.handle), e.kind, e.title, e.place, year(e.from), year(e.to), String(e.to).toLowerCase() === 'now', i]))))
out.push(insertRaw('user_skills', ['user_id', 'skill_id', 'role', 'level', 'years', 'goal', 'added_on', 'position'], PEOPLE.flatMap((p) => [
  ...p.teaches.map((t, i) => [uid(p.handle), t.skill, 'teach', t.level, t.years, null, joinedOn(p.joined), i]),
  ...p.wants.map((w, i) => [uid(p.handle), w.skill, 'learn', null, null, w.goal || null, joinedOn(p.joined), i]),
])))
out.push(insertRaw('availability', ['user_id', 'day', 'part'], PEOPLE.flatMap((p) => p.avail.map((code) => { const [d, part] = code.split('-'); return [uid(p.handle), DAYS.indexOf(d), part] }))))
out.push(insertRaw('reviews', ['author_id', 'subject_id', 'skill_id', 'body'], PEOPLE.flatMap((p) => p.reviews.map((r) => [uid(r.by), uid(p.handle), r.skill, r.text]))))
out.push(insertRaw('lessons', ['user_id', 'skill_id', 'title', 'tried', 'why_failed', 'learned', 'visibility', 'happened_on'],
  PEOPLE.flatMap((p) => p.lessons.map((l) => [uid(p.handle), l.skill, l.title, l.tried, l.why, l.lesson, 'public', `${l.at}-01`]))))

// ── The demo member: Ari Navarro and their history ──
// Signing in as Ari goes through the website's "Try the demo" button, so the password is random and never used.
const demoHash = bcrypt.hashSync(randomBytes(24).toString('base64url'), 10)
const start = DEMO_GROWTH.start
const me = DEMO_ME
out.push('-- The demo member (sign in with the website\'s "Try the demo" button)')
out.push(insert('users',
  ['handle', 'email', 'password_hash', 'name', 'headline', 'bio', 'teach_style', 'city', 'country', 'tz_offset', 'main_field', 'meets_online', 'meets_in_person', 'github', 'avatar_seed', 'member_no', 'joined_on'],
  [[me.handle, 'demo@oren.test', demoHash, me.name, me.headline, me.bio, me.style, me.city, me.country, me.tz, me.field, me.format.includes('online'), me.format.includes('in-person'), me.github, me.avatarSeed || null, me.number, start]]))
out.push(insertRaw('user_languages', ['user_id', 'language'], me.languages.map((l) => [uid(me.handle), l])))
out.push(insertRaw('education', ['user_id', 'kind', 'title', 'place', 'from_year', 'to_year', 'ongoing', 'position'],
  me.education.map((e, i) => [uid(me.handle), e.kind, e.title, e.place, year(e.from), year(e.to), String(e.to).toLowerCase() === 'now', i])))
out.push(insertRaw('user_skills', ['user_id', 'skill_id', 'role', 'level', 'years', 'goal', 'added_on', 'position'], [
  ...me.teaches.map((t, i) => [uid(me.handle), t.skill, 'teach', t.level, t.years, null, start, i]),
  ...me.wants.map((w, i) => [uid(me.handle), w.skill, 'learn', null, null, w.goal, DEMO_GROWTH.wished?.[w.skill] || start, i]),
]))
out.push(insertRaw('availability', ['user_id', 'day', 'part'], me.avail.map((code) => { const [d, part] = code.split('-'); return [uid(me.handle), DAYS.indexOf(d), part] })))

// Ari's swaps. Each partner teaches one skill and Ari teaches one back; notes are what Ari wrote afterwards.
const PERSON = Object.fromEntries(PEOPLE.map((p) => [p.handle, p]))
const mine = new Set([...me.teaches.map((t) => t.skill), ...me.wants.map((w) => w.skill), ...Object.keys(DEMO_GROWTH.learned)])
const ariTeachesTo = (h, fallback) => PERSON[h].wants.map((w) => w.skill).find((s) => me.teaches.some((t) => t.skill === s)) || fallback
const partnerTeaches = (h) => PERSON[h].teaches.map((t) => t.skill).find((s) => !mine.has(s)) || PERSON[h].teaches[0].skill
const EXTRA = {
  java: ['Constructors and this: an object sets itself up the moment it is built.', 'Lists and maps from java.util: ArrayList for order, HashMap for lookups.', 'Checked exceptions are a contract, so the compiler makes you deal with them.', 'Streams turned my ten-line loops into three readable lines.'],
  docker: ['Volumes keep my database data when the container restarts.', 'Ports: the left number is my laptop, the right one is inside the container.'],
  react: ['Lift state up to the closest shared parent instead of keeping two copies in sync.'],
}
const swaps = []
for (const [skill, l] of Object.entries(DEMO_GROWTH.learned)) {
  const partner = l.from[0]
  const notes = [...l.notes].sort((a, b) => a.at.localeCompare(b.at))
  const extra = [...(EXTRA[skill] || [])]
  // spread the sessions weekly from the first one; keep the notes the website already shows on their dates
  const dates = [], first = new Date(`${l.since}T00:00Z`)
  for (let k = 0; dates.length < l.sessions; k++) {
    const d = new Date(first.getTime() + k * 7 * 864e5).toISOString().slice(0, 10)
    if (!dates.includes(d)) dates.push(d)
  }
  for (const n of notes) if (!dates.includes(n.at)) dates[dates.findIndex((d) => d > n.at) === -1 ? dates.length - 1 : dates.findIndex((d) => d > n.at)] = n.at
  dates.sort()
  const teach = ariTeachesTo(partner, 'python')
  dates.forEach((d) => swaps.push({ partner, ariTeaches: teach, partnerTeaches: skill, on: d, note: notes.find((n) => n.at === d)?.text || extra.shift() || `Practised ${skill} together.` }))
}
// people Ari taught without writing anything down about their side
for (const [skill, list] of Object.entries(DEMO_GROWTH.taught)) {
  for (const t of list) {
    if (swaps.some((s) => s.partner === t.who && s.ariTeaches === skill)) continue
    swaps.push({ partner: t.who, ariTeaches: skill, partnerTeaches: partnerTeaches(t.who), on: t.at, note: null })
  }
}
swaps.sort((a, b) => a.on.localeCompare(b.on))
const partners = [...new Set(swaps.map((s) => s.partner)), 'danarashid']
out.push('-- Ari matched with everyone they swapped with')
out.push(insertRaw('swipes', ['swiper_id', 'target_id', 'decision', 'decided_at'], partners.flatMap((h) => [
  [uid(me.handle), uid(h), 'like', `${start} 12:00+03`],
  [uid(h), uid(me.handle), 'like', `${start} 12:00+03`],
]), ' ON CONFLICT (swiper_id, target_id) DO NOTHING'))
out.push('-- Past sessions. Learning notes are added one by one so the triggers endorse Ari exactly as they would live.')
for (const s of swaps) {
  out.push(`WITH s AS (INSERT INTO swap_sessions (proposer_id, partner_id, proposer_teaches, partner_teaches, starts_at, minutes, meeting_link, status) VALUES (${uid(me.handle).raw}, ${uid(s.partner).raw}, ${lit(s.ariTeaches)}, ${lit(s.partnerTeaches)}, ${lit(`${s.on} 18:00+03`)}, 120, ${lit(`https://meet.jit.si/oren-${me.handle}-${s.partner}`)}, 'completed') RETURNING id)` +
    (s.note ? `\nINSERT INTO learning_log (session_id, learner_id, skill_id, note, logged_on) SELECT id, ${uid(me.handle).raw}, ${lit(s.partnerTeaches)}, ${lit(s.note)}, ${lit(s.on)} FROM s;` : '\nSELECT id FROM s;'))
}
out.push('-- Ari feels confident about the skills the website marks as such')
out.push(insertRaw('skill_confidence', ['user_id', 'skill_id', 'confident'], Object.entries(DEMO_GROWTH.learned).filter(([, l]) => l.confident).map(([skill]) => [uid(me.handle), skill, true])))
out.push('-- Ari\'s lessons (the roots of the tree)')
out.push(insertRaw('lessons', ['user_id', 'skill_id', 'title', 'tried', 'why_failed', 'learned', 'visibility', 'happened_on'],
  DEMO_GROWTH.lessons.map((l) => [uid(me.handle), l.skill, l.title, l.tried, l.why, l.lesson, l.visibility, l.at])))
out.push('-- An upcoming session and two conversations')
out.push(`INSERT INTO swap_sessions (proposer_id, partner_id, proposer_teaches, partner_teaches, starts_at, minutes, meeting_link, status) VALUES (${uid(me.handle).raw}, ${uid('danarashid').raw}, 'python', 'publicspeaking', '2026-11-24 18:00+03', 120, 'https://meet.jit.si/oren-arinavarro-danarashid', 'confirmed');`)
out.push(insertRaw('messages', ['sender_id', 'receiver_id', 'body', 'sent_at'], [
  [uid('danarashid'), uid(me.handle), 'Your Python session saved my spreadsheet. Ready to rehearse your project talk next week?', '2026-11-04 10:12+03'],
  [uid(me.handle), uid('danarashid'), 'Yes! I will bring the slides. Be honest about the umms.', '2026-11-04 10:30+03'],
  [uid('minapark'), uid(me.handle), 'Next time: forms in React. Bring the portfolio repo.', '2026-10-18 20:05+03'],
]))
writeFileSync(join(here, '..', 'db', 'seed.sql'), out.join('\n'))
console.log(`seed.sql: ${AREAS.length} areas, ${FIELDS.length} fields, ${SKILLS.length} skills, ${PEOPLE.length} sample members, demo member with ${swaps.length} past sessions (${swaps.filter((s) => s.note).length} with notes)`)
